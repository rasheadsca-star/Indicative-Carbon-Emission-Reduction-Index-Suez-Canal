import test from "node:test";
import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {validateHistoricalSeries,buildHistoricalPerformance,backtestHistoricalTraffic} from "./historical-performance.mjs";
const history=JSON.parse(await readFile(new URL("../data/sca-official-annual-history-1975-2025.json",import.meta.url),"utf8"));
const detail=JSON.parse(await readFile(new URL("../data/sca-official-monthly-2024-2025.json",import.meta.url),"utf8"));
test("official annual series has 51 complete year labels and matches 2023–25 detailed monthly data",()=>{
 assert.equal(validateHistoricalSeries(history,detail),true);
 assert.equal(history.annual.length,51);
 assert.equal(history.annual[0].year,1975);
 assert.equal(history.annual.at(-1).year,2025);
 assert.equal(history.annual.find(x=>x.year===2023).vessels,26434);
});
test("1975 partial year and anomalous 2004 net tonnage are explicitly quarantined",()=>{
 const a=buildHistoricalPerformance(history,detail);
 const a75=a.annual.find(x=>x.year===1975);
 const a76=a.annual.find(x=>x.year===1976);
 const a03=a.annual.find(x=>x.year===2003);
 const a04=a.annual.find(x=>x.year===2004);
 const a05=a.annual.find(x=>x.year===2005);
 assert.equal(a75.classification,"PARTIAL_YEAR");
 assert.equal(a76.vesselsYoYPct,null);
 assert.equal(a04.netTonnageThousands,62127);
 assert.equal(a04.netTonnesPerVessel,null);
 assert.equal(a04.tonnageYoYPct,null);
 assert.equal(a05.tonnageYoYPct,null);
 assert.notEqual(a03.netTonnesPerVessel,null);
 assert.equal(a.verifiedAvoidedCO2Tonnes,null);
});
test("historical shocks, annual changes and recovery gap are grounded",()=>{
 const a=buildHistoricalPerformance(history,detail);
 const y=yr=>a.annual.find(x=>x.year===yr);
 assert.equal(y(2009).vesselsYoYPct,-19.55);
 assert.equal(y(2024).vesselsYoYPct,-50.02);
 assert.equal(y(2025).vesselsYoYPct,-3.44);
 assert.equal(y(2025).tonnageYoYPct,-0.47);
 assert.equal(a.peakShipYear.year,2023);
 assert.equal(a.latest.year,2025);
 assert.equal(a.comparedTo2023.recoveryGapTo2023VesselsPct,51.74);
});
test("walk forward uses only earlier years and reports errors for both the crisis year and recovery",()=>{
 const b=backtestHistoricalTraffic(history,{from:2023,to:2025});
 const r24=b.runs.find(x=>x.year===2024);
 const r25=b.runs.find(x=>x.year===2025);
 assert.equal(b.runs.length,3);
 assert.equal(r24.actual,13213);
 assert.equal(r24.forecasts.lastYear,26434);
 assert.equal(r24.forecasts.movingAverage3,(20694+23851+26434)/3);
 assert.equal(r25.forecasts.lastYear,13213);
 assert.ok(b.lastYear.mapePct>0);
 assert.equal(b.state,"HISTORICAL_TRAFFIC_FORECAST_BACKTEST_NOT_EMISSIONS");
});
